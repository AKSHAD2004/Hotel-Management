/**
 * Returns localized name and description for any item based on active language ('en' | 'mr' | 'hi')
 */
export const getLocalizedDish = (item, language = 'en') => {
  if (!item) return { name: '', description: '' };
  
  const trans = MENU_TRANSLATIONS[item.id];
  if (trans && trans[language]) {
    return {
      name: trans[language].name,
      description: trans[language].description
    };
  }

  // Check custom item localized properties or fallback
  if (language === 'mr' && item.name_mr) {
    return { name: item.name_mr, description: item.description_mr || item.description };
  }
  if (language === 'hi' && item.name_hi) {
    return { name: item.name_hi, description: item.description_hi || item.description };
  }

  return {
    name: item.name,
    description: item.description
  };
};
